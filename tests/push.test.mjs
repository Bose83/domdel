import {test} from 'node:test';
import assert from 'node:assert/strict';
import {PGlite} from '@electric-sql/pglite';
import {readFile} from 'node:fs/promises';
import {seed} from '../server/engine.mjs';
import {validateSubscription,notices,sendReminders,subscriptionAction} from '../server/push.mjs';
const subscription={endpoint:'https://fcm.googleapis.com/fcm/send/test-token',keys:{p256dh:'a'.repeat(87),auth:'b'.repeat(22)}};
test('push filters, quiet hours, SSRF rejection, delivery deduplication and revocation',async()=>{
 assert.deepEqual(validateSubscription(subscription),subscription);
 for(const endpoint of ['http://127.0.0.1/a','https://evil.test/a','https://fcm.googleapis.com.evil.test/a','https://fcm.googleapis.com:444/a','https://user:password@fcm.googleapis.com/a'])assert.throws(()=>validateSubscription({...subscription,endpoint}));
 const room=seed('Дом','Мама'),p=room.members[0],now=Date.parse('2026-10-18T12:00:00+04:00');
 room.events.push({id:'event',at:now+600000,remind:30,people:[],answers:{}});
 room.messages.push({id:'m',author:'other',at:now-100,text:'@Мама, завтра театр'});
 assert.equal(notices(room,p,now).length,2);
 assert.equal(notices(room,p,Date.parse('2026-10-18T23:00:00+04:00')).length,0);
 p.prefs.notifications='off';assert.equal(notices(room,p,now).length,0);p.prefs.notifications='important';p.prefs.quietStart=p.prefs.quietEnd='00:00';
 const db=new PGlite();for(const file of ['202610180001_initial.sql','202610180002_push.sql'])await db.exec(await readFile('netlify/database/migrations/'+file,'utf8'));
 const account=crypto.randomUUID();await db.query('INSERT INTO accounts VALUES($1,$2,$3,$4,$5,$6)',[account,'user','Имя','hash','recovery',Date.now()]);
 room.id=crypto.randomUUID();room.events[0].at=Date.now()+600000;room.messages=[];
 await db.query('INSERT INTO rooms(id,creator,code,data) VALUES($1,$2,$3,$4)',[room.id,account,room.code,JSON.stringify(room)]);
 await db.query('INSERT INTO memberships VALUES($1,$2,$3)',[account,room.id,p.id]);
 await db.query('INSERT INTO sessions(token_hash,account_id,expires_at,touched_at) VALUES($1,$2,$3,$4)',['session',account,Date.now()+600000,Date.now()]);
 const env={VAPID_PUBLIC_KEY:'public',VAPID_PRIVATE_KEY:'private',URL:'https://app.test'};
 await subscriptionAction(db,'session','push-enable',{subscription},env);
 let calls=0;const send=async()=>{calls++};
 assert.equal((await sendReminders(db,env,send)).sent,1);
 await db.query('UPDATE push_subscriptions SET last_sent=0');
 assert.equal((await sendReminders(db,env,send)).sent,0);assert.equal(calls,1);
 await db.query('DELETE FROM sessions');assert.equal((await db.query('SELECT * FROM push_subscriptions')).rows.length,0);
 await db.close();
});
